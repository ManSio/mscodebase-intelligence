"""Состояние автоиндексации: идёт ли она прямо сейчас.

Зачем отдельный модуль: `require_ready_project` ждёт первые чанки, и ему нужен
честный ответ «индексация идёт» vs «её никто не запускал». В `get_status()`
такого признака нет (`reindex_in_progress` покрывает только явную
переиндексацию), поэтому ожидание на реально пустом проекте стоило полный
бюджет (замер ревью 2026-11-16: 8 с на каждый первый запрос).

Состояние — на процесс: MCP-сервер однопроцессный, автоиндексация живёт в его
event loop. `threading.Event` безопасен из потока и из корутин.
"""

from __future__ import annotations

import threading

_running = threading.Event()


def mark_started() -> None:
    """Автоиндексация началась."""
    _running.set()


def mark_finished() -> None:
    """Автоиндексация завершилась (успех или ошибка)."""
    _running.clear()


def is_running() -> bool:
    """Идёт ли автоиндексация прямо сейчас."""
    return _running.is_set()
